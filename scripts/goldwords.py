PUNCT = "，。；：、！？（）「」『』《》〈〉·…—　 \n\t"


def _depunct(s):
    """去标点与空白，只留汉字。古书多不用标点，用户输入亦常省略"""
    return "".join(c for c in s if c not in PUNCT)


def _match_chapters(text):
    """找出输入文本所扣的章节"""
    hits = []
    # 直接引用原文片段。先去标点再匹配——「道可道，非常道」与「道可道非常道」应视为同一句
    flat_text = _depunct(text)
    for cid, orig in CORPUS.items():
        flat_orig = _depunct(orig)
        for n in (12, 9, 6):
            found = False
            for i in range(0, max(0, len(flat_orig) - n + 1)):
                if flat_orig[i:i + n] in flat_text:
                    hits.append((cid, n, orig[i:i + n]))
                    found = True
                    break
            if found:
                break
    # 显式章号
    import re as _re
    for m in _re.finditer(r"第\s*([0-9一二三四五六七八九十]+)\s*章", text):
        raw = m.group(1)
        cn = {"一":1,"二":2,"三":3,"四":4,"五":5,"六":6,"七":7,"八":8,"九":9}
        cid = int(raw) if raw.isdigit() else (cn.get(raw, 0) if raw in cn else 0)
        if 1 <= cid <= 81:
            hits.append((cid, 99, f"第{cid}章"))
    return hits


def judge_ferocity(text):
    """
    火候判定：宽进严出。
    返回 dict(score, level, verdict, reasons, missing, chapters)
    """
    text = (text or "").strip()
    reasons, missing = [], []
    score = 0

    # 一、是否扣原文（根）—— 权重最高
    hits = _match_chapters(text)
    chaps = sorted({h[0] for h in hits})
    if chaps:
        best = max(h[1] for h in hits)
        if best >= 12:
            score += 45
            reasons.append(f"直引原文，扣第 {'、'.join(map(str, chaps[:5]))} 章（{best} 字连续命中）")
        elif best >= 9:
            score += 35
            reasons.append(f"近引原文章句，扣第 {'、'.join(map(str, chaps[:5]))} 章")
        elif best >= 6:
            score += 25
            reasons.append(f"文中含原文片段，关联第 {'、'.join(map(str, chaps[:5]))} 章")
        else:
            score += 15
            reasons.append(f"显式提及第 {'、'.join(map(str, chaps[:5]))} 章")
    else:
        missing.append("未扣住任何原文章句——无根之木，炼不出丹")

    # 二、是否有实质（料）
    L = len(text)
    if L < 8:
        missing.append("篇幅过短，不足成丹")
    elif L < 30:
        score += 8
        reasons.append("有实义，然尚简")
    elif L < 300:
        score += 20
        reasons.append(f"篇幅适中（{L} 字），可炼")
    else:
        score += 18
        reasons.append(f"material 充足（{L} 字），需先剔芜存菁")

    # 三、是否合义理（向）
    yili = [w for w in YILI_WORDS if w in text]
    if len(yili) >= 5:
        score += 25
        reasons.append(f"义理词密集（{'、'.join(sorted(yili, key=len, reverse=True)[:6])}），在道上")
    elif len(yili) >= 2:
        score += 15
        reasons.append(f"涉义理（{'、'.join(sorted(yili, key=len, reverse=True)[:5])}）")
    elif len(yili) == 1:
        score += 6
        reasons.append(f"仅触及「{yili[0]}」一隅，未成体系")
    else:
        missing.append("未涉道之语汇，恐非《道德经》所能答")

    # 四、扣分项：空话与绝对化
    import re as _re
    for pat, label in EMPTY_PATTERNS:
        if _re.search(pat, text, _re.M):
            score -= 22
            missing.append(f"见「{label}」之弊，非道之实")
            break

    # 定级
    score = max(0, min(100, score))
    if score >= 75:
        level = "上品·可炼"
        verdict = "火候已足，可结金丹。"
        ok = True
    elif score >= 55:
        level = "中品·可炼"
        verdict = "火候尚可，可结丹，然需精炼。"
        ok = True
    elif score >= 35:
        level = "下品·勉炼"
        verdict = "料薄根浅，可试炼，恐难成大丹。"
        ok = True
    else:
        level = "火候未到"
        verdict = "此物入炉，炼不出丹。请引原文章句，或就此章之义理申说。"
        ok = False

    # 无根者一律不结丹（宽进严出的底线）
    if not chaps:
        ok = False
        level = "火候未到"
        verdict = "无原文之根，不成金丹。请扣定章节与章句再来。"

    return {
        "score": score, "level": level, "verdict": verdict,
        "reasons": reasons, "missing": missing,
        "chapters": chaps, "ok": ok,
    }


